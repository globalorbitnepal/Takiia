#!/usr/bin/env node
/**
 * Update only the takiia-web process in the Takiia ecosystem file so Next.js
 * binds 127.0.0.1:3034 and PM2 wait_ready waits for /api/health.
 * Refuses to write if any non-Takiia app names are present.
 */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const ecosystemPath = process.argv[2];
if (!ecosystemPath) {
  console.error('usage: patch-takiia-web-ecosystem.mjs <ecosystem.config.cjs>');
  process.exit(1);
}

const require = createRequire(import.meta.url);
const cfg = require(ecosystemPath);
const apps = cfg?.apps;
if (!Array.isArray(apps) || apps.length === 0) {
  console.error('ecosystem has no apps; refusing to patch');
  process.exit(1);
}

const allowed = new Set(['takiia-api', 'takiia-web']);
const unexpected = apps.map((app) => app?.name).filter((name) => !allowed.has(name));
if (unexpected.length) {
  console.error(`refusing to patch ecosystem; unexpected apps: ${unexpected.join(', ')}`);
  process.exit(1);
}

const web = apps.find((app) => app.name === 'takiia-web');
if (!web) {
  console.error('takiia-web missing from ecosystem; refusing to patch');
  process.exit(1);
}

const alreadyPatched =
  web.script === 'scripts/deploy/start-web.cjs' &&
  web.wait_ready === true &&
  web.env_production?.TAKIIA_WEB_PORT === '3034';

if (alreadyPatched) {
  console.log('takiia-web ecosystem already uses start-web.cjs wait_ready on 3034');
  console.log('STATUS=unchanged');
  process.exit(0);
}

web.script = 'scripts/deploy/start-web.cjs';
web.interpreter = 'node';
delete web.args;
web.wait_ready = true;
web.listen_timeout = 20000;
web.kill_timeout = 10000;
web.env_production = {
  ...(web.env_production ?? {}),
  NODE_ENV: 'production',
  TAKIIA_WEB_HOST: '127.0.0.1',
  TAKIIA_WEB_PORT: '3034',
};

const serialized = `/**
 * Generated by scripts/deploy/lib/patch-takiia-web-ecosystem.mjs
 * Takiia PM2 apps only — do not add other sites here.
 */
module.exports = ${JSON.stringify({ apps }, null, 2)};
`;
writeFileSync(ecosystemPath, serialized, 'utf8');
console.log('Patched takiia-web to start-web.cjs (127.0.0.1:3034, wait_ready)');
console.log('STATUS=patched');
